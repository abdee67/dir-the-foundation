--   • reads go through createSignedUrl() via service_role (bypasses RLS)
--   • anon and authenticated users cannot read directly

-- ---------------------------------------------------------------------
-- 3. Allow anon to read only payment instructions.
--    Payment method instructions (payments.instructions key) are stored
--    in org_settings and displayed on the storefront payment page.
--    Gated on the org being active — same pattern as orgs_anon_select_active
--    in 0004_storefront_public_org_read.sql.
-- ---------------------------------------------------------------------
DROP POLICY IF EXISTS org_settings_anon_select ON public.org_settings;
CREATE POLICY org_settings_anon_select ON public.org_settings
  FOR SELECT TO anon
  USING (
    key = 'payments.instructions'
    AND
    EXISTS (
      SELECT 1 FROM public.orgs o
      WHERE o.id = org_settings.org_id AND o.is_active = true
    )
  );

