-- ---------------------------------------------------------------------
-- 1. Public order-tracking function.
--    SECURITY DEFINER so anon can call it without any direct table access.
--    Returns only safe public-facing fields — never admin notes, risk
--    data, full addresses, or internal metadata.
--    Matches the customer flow: order number + phone → status timeline.
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION get_order_status(p_order_no text, p_phone text)
RETURNS TABLE (
  order_no       text,
  status         text,
  payment_status text,
  customer_name  text,
  placed_at      timestamptz,
  events         jsonb
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
BEGIN
  RETURN QUERY
  SELECT
    o.order_no,
    o.status::text,
    o.payment_status::text,
    o.customer_name,
    o.placed_at,
    COALESCE(
      (
        SELECT jsonb_agg(
          jsonb_build_object(
            'type',       oe.type,
            'message',    oe.message,
            'created_at', oe.created_at
          )
          ORDER BY oe.created_at
        )
        FROM order_events oe
        WHERE oe.order_id = o.id
          AND oe.type = 'status'  -- status-change events only; never admin notes
      ),
      '[]'::jsonb
    ) AS events
  FROM orders o
  WHERE o.order_no      = p_order_no
    AND o.customer_phone = p_phone
  LIMIT 1;
END;
$$;

GRANT EXECUTE ON FUNCTION get_order_status(text, text) TO anon;
GRANT EXECUTE ON FUNCTION get_order_status(text, text) TO authenticated;

-- ---------------------------------------------------------------------
-- 2. Private storage bucket for payment proof screenshots.
--    public = false — files are never accessible via a public URL.
--    Served only through server-side signed URLs (5-minute expiry)
--    generated by getPaymentScreenshotUrl() in src/modules/storefront/actions.ts.
-- ---------------------------------------------------------------------
INSERT INTO storage.buckets (id, name, public)
VALUES ('payment-proofs', 'payment-proofs', false)
ON CONFLICT (id) DO NOTHING;

-- No storage RLS policies needed here:
